"""Tests for the experimental quadrature-based Pareto/NBD log-likelihood.

Reference values were generated by ``scripts/data_generators/pareto_nbd_quadrature_reference.py``
with mpmath at 40 significant digits.
"""

from pathlib import Path

import numpy as np
import pandas as pd
import pymc as pm
import pytensor
import pytensor.tensor as pt
import pytest
from numpy.testing import assert_allclose, assert_almost_equal
from pymc.logprob.utils import ParameterValueError
from pytensor.compile.mode import Mode, get_mode

from pymc_marketing.clv.distributions import ParetoNBD, _pareto_nbd_logp_quadrature
from pymc_marketing.clv.models import ParetoNBDModel

REFERENCE_PATH = Path(__file__).parent / "data" / "pareto_nbd_quadrature_reference.npz"
CDNOW_TRUTH = np.array([0.5534, 10.5802, 0.6061, 11.6562])


@pytest.fixture(scope="module")
def reference() -> dict[str, np.ndarray]:
    with np.load(REFERENCE_PATH) as data:
        return {key: data[key] for key in data.files}


def _unpack(reference):
    r, alpha, s, beta = reference["params"].T
    t_x, x, T = reference["values"].T
    return r, alpha, s, beta, np.stack([t_x, x], axis=1), T


def _quadrature(reference, **kwargs) -> np.ndarray:
    r, alpha, s, beta, value, T = _unpack(reference)
    return _pareto_nbd_logp_quadrature(value, r, alpha, s, beta, T, **kwargs).eval()


def _symbolic_logp_and_grad(reference, **kwargs):
    """Per-row logp and per-row partials w.r.t. (r, alpha, s, beta) as a compiled function."""
    r, alpha, s, beta, value, T = _unpack(reference)
    params = [pt.dvector(name) for name in ("r", "alpha", "s", "beta")]
    logp = _pareto_nbd_logp_quadrature(value, *params, T, **kwargs)
    return params, [logp, *pytensor.grad(logp.sum(), params)], (r, alpha, s, beta)


class TestQuadratureLogp:
    @pytest.mark.parametrize(
        "log_substitution, n_nodes, x_max, atol",
        [
            (True, 128, 500, 1e-9),
            (True, 64, 80, 1e-7),
            (True, 32, 20, 1e-4),
            (False, 512, 20, 1e-7),
        ],
    )
    def test_matches_reference(self, reference, log_substitution, n_nodes, x_max, atol):
        x = reference["values"][:, 1]
        logp = _quadrature(
            reference, n_nodes=n_nodes, log_substitution=log_substitution
        )
        mask = x <= x_max
        # rtol covers float64 roundoff on the gammaln term, which reaches ~3000 at x = 500
        assert_allclose(logp[mask], reference["logp_ref"][mask], rtol=1e-10, atol=atol)

    def test_plain_rule_is_inaccurate(self, reference):
        """Documents why the log substitution is the default."""
        x = reference["values"][:, 1]
        err = np.abs(
            _quadrature(reference, n_nodes=128, log_substitution=False)
            - reference["logp_ref"]
        )
        assert err[x <= 20].max() > 1e-2

    def test_matches_hyp2f1_where_finite(self, reference):
        r, alpha, s, beta, value, T = _unpack(reference)
        current = pm.logp(
            ParetoNBD.dist(r=r, alpha=alpha, s=s, beta=beta, T=T), value
        ).eval()
        quadrature = _quadrature(reference)

        finite = np.isfinite(current)
        # hyp2f1 overflows or returns NaN on part of the grid; the quadrature does not
        assert 0 < (~finite).sum() < len(current)
        assert np.isfinite(quadrature).all()
        assert_allclose(quadrature[finite], current[finite], rtol=1e-10, atol=1e-8)

    def test_gradients_match_reference(self, reference):
        params, outputs, theta = _symbolic_logp_and_grad(reference)
        fn = pytensor.function(params, outputs)
        _, *grads = fn(*theta)
        assert_allclose(np.stack(grads, axis=1), reference["grad_ref"], rtol=1e-6)

    def test_gradients_match_hyp2f1_where_finite(self, reference):
        r, alpha, s, beta, value, T = _unpack(reference)
        params = [pt.dvector(name) for name in ("r", "alpha", "s", "beta")]
        current = pm.logp(ParetoNBD.dist(*params, T=T), value)
        fn = pytensor.function(params, pytensor.grad(current.sum(), params))
        hyp2f1_grad = np.stack(fn(r, alpha, s, beta), axis=1)

        quad_params, outputs, theta = _symbolic_logp_and_grad(reference)
        quad_grad = np.stack(
            pytensor.function(quad_params, outputs[1:])(*theta), axis=1
        )

        finite = np.isfinite(hyp2f1_grad).all(axis=1)
        assert 0 < (~finite).sum() < len(finite)
        assert np.isfinite(quad_grad).all()
        assert_allclose(quad_grad[finite], hyp2f1_grad[finite], rtol=1e-5, atol=1e-8)

    @pytest.mark.parametrize("log_substitution", [False, True])
    @pytest.mark.parametrize(
        "theta",
        [(0.55, 10.58, 0.61, 11.67), (0.55, 10.58, 0.61, 10.58)],
        ids=["alpha_ne_beta", "alpha_eq_beta"],
    )
    def test_edge_cases_are_finite(self, log_substitution, theta):
        """t_x == T (zero-width integral), non-repeat customers and alpha == beta."""
        T = 52.0
        value = np.array([[T, 3.0], [0.0, 0.0], [T, 0.0], [T - 1e-9, 5.0]])
        params = [pt.dscalar(name) for name in ("r", "alpha", "s", "beta")]
        logp = _pareto_nbd_logp_quadrature(
            value, *params, T, log_substitution=log_substitution
        )
        fn = pytensor.function(params, [logp, *pytensor.grad(logp.sum(), params)])
        out, *grads = fn(*theta)
        assert np.isfinite(out).all()
        assert all(np.isfinite(g) for g in grads)

        expected = pm.logp(ParetoNBD.dist(*theta, T=T), value).eval()
        assert_allclose(out, expected, rtol=0, atol=1e-8)

    def test_invalid_values_and_parameters(self):
        kwargs = dict(r=0.55, alpha=10.58, s=0.61, beta=11.67, T=10)
        for value in ([3, -1], [-1, 1.5], [11, 1.5]):
            assert (
                _pareto_nbd_logp_quadrature(np.array(value), **kwargs).eval() == -np.inf
            )

        for bad in ("r", "alpha", "s", "beta"):
            with pytest.raises(ParameterValueError):
                _pareto_nbd_logp_quadrature(
                    np.array([1.5, 1]), **{**kwargs, bad: -1.0}
                ).eval()

    # Same cases and reference values as TestParetoNBD.test_pareto_nbd
    @pytest.mark.parametrize(
        "value, r, alpha, s, beta, T, expected_logp",
        [
            (np.array([1.5, 1]), 0.55, 10.58, 0.61, 11.67, 12, np.array(-4.00694866)),
            (
                np.array([1.5, 1]),
                [0.45, 0.55],
                10.58,
                0.61,
                11.67,
                12,
                np.array([-4.14770211, -4.00694866]),
            ),
            (
                np.array([1.5, 1]),
                [0.45, 0.55],
                10.58,
                [0.71, 0.61],
                11.67,
                12,
                np.array([-4.13593316, -4.00694866]),
            ),
            (
                np.array([[1.5, 1], [5.3, 4], [6, 2]]),
                0.55,
                11.67,
                0.61,
                10.58,
                [12, 10, 8],
                np.array([-4.03618538, -10.72932589, -6.66878882]),
            ),
            (
                np.array([1.5, 1]),
                0.55,
                10.58,
                0.61,
                np.full((5, 3), 11.67),
                12,
                np.full((5, 3), -4.00694866),
            ),
        ],
    )
    def test_batch_shapes(self, value, r, alpha, s, beta, T, expected_logp):
        logp = _pareto_nbd_logp_quadrature(value, r, alpha, s, beta, T).eval()
        assert logp.shape == expected_logp.shape
        assert_almost_equal(logp, expected_logp, decimal=6)

    @pytest.mark.parametrize("linker", ["cvm", "numba", "jax"])
    def test_backends_agree(self, reference, linker):
        if linker == "numba":
            pytest.importorskip("numba")
            mode = get_mode("NUMBA")
        elif linker == "jax":
            pytest.importorskip("jax")
            mode = get_mode("JAX")
        else:
            mode = Mode(linker="cvm", optimizer="fast_run")

        params, outputs, theta = _symbolic_logp_and_grad(reference)
        expected = pytensor.function(params, outputs, mode=get_mode("FAST_COMPILE"))(
            *theta
        )
        actual = pytensor.function(params, outputs, mode=mode)(*theta)
        for got, want in zip(actual, expected, strict=True):
            assert_allclose(np.asarray(got), want, rtol=1e-8, atol=1e-8)


def _build_quadrature_model(data: pd.DataFrame) -> pm.Model:
    """Mirror ``ParetoNBDModel.build_model`` with the quadrature logp via ``pm.CustomDist``."""
    config = ParetoNBDModel().default_model_config
    coords = {
        "customer_id": data["customer_id"],
        "obs_var": ["recency", "frequency"],
    }
    with pm.Model(coords=coords) as model:
        params = [
            config[name].create_variable(name) for name in ("r", "alpha", "s", "beta")
        ]
        pm.CustomDist(
            "recency_frequency",
            *params,
            data["T"].to_numpy(dtype=float),
            logp=_pareto_nbd_logp_quadrature,
            signature="(),(),(),(),()->(2)",
            observed=np.stack((data["recency"], data["frequency"]), axis=1),
            dims=["customer_id", "obs_var"],
        )
    return model


@pytest.mark.slow
@pytest.mark.parametrize("method, rtol", [("map", 0.2), ("mcmc", 0.1)])
def test_end_to_end_fit(method, rtol):
    data = pd.read_csv("data/clv_quickstart.csv")
    data["customer_id"] = data.index
    model = _build_quadrature_model(data)

    with model:
        if method == "map":
            result = pm.find_MAP(progressbar=False)
            estimate = [float(result[name]) for name in ("r", "alpha", "s", "beta")]
        else:
            idata = pm.sample(
                chains=2, tune=500, draws=500, random_seed=42, progressbar=False
            )
            estimate = [
                float(idata.posterior[name].mean())
                for name in ("r", "alpha", "s", "beta")
            ]

    assert_allclose(estimate, CDNOW_TRUTH, rtol=rtol)
